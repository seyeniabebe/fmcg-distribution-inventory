-- 7. Ensure 'debt_payment_installments' table exists for partial debt repayments & receipts
CREATE TABLE IF NOT EXISTS debt_payment_installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    customer_name VARCHAR(255) NOT NULL,
    agent_name VARCHAR(255) NOT NULL,
    amount NUMERIC(38,2) NOT NULL,
    payment_method VARCHAR(50) NOT NULL,
    payment_ref TEXT,
    payment_screenshot_path VARCHAR(255),
    paid_at TIMESTAMP NOT NULL,
    remaining_after NUMERIC(38,2) NOT NULL DEFAULT 0.00,
    settled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_debt_installments_sale_id ON debt_payment_installments(sale_id);
CREATE INDEX IF NOT EXISTS idx_debt_installments_paid_at ON debt_payment_installments(paid_at);
CREATE INDEX IF NOT EXISTS idx_debt_installments_agent ON debt_payment_installments(agent_name);

-- 8. Ensure 'app_messages' table exists for admin-to-agent messaging
CREATE TABLE IF NOT EXISTS app_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_username VARCHAR(255) NOT NULL,
    sender_full_name VARCHAR(255) NOT NULL,
    sender_role VARCHAR(50) NOT NULL,
    recipient_username VARCHAR(255) NOT NULL,
    recipient_full_name VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    sent_at TIMESTAMP NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_messages_recipient ON app_messages(recipient_username);
CREATE INDEX IF NOT EXISTS idx_messages_sender ON app_messages(sender_username);
CREATE INDEX IF NOT EXISTS idx_messages_sent_at ON app_messages(sent_at);

-- 9. Ensure 'admin_notifications' table exists for real-time sales & stock-in alerts
CREATE TABLE IF NOT EXISTS admin_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_type VARCHAR(100) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    agent_name VARCHAR(255),
    product_info VARCHAR(255),
    quantity INTEGER,
    amount NUMERIC(38,2),
    customer_name VARCHAR(255),
    reference VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_notifications_created_at ON admin_notifications(created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_is_read ON admin_notifications(is_read);

-- 10. General indexes
CREATE INDEX IF NOT EXISTS idx_sale_transactions_agent_name ON sale_transactions(agent_name);
CREATE INDEX IF NOT EXISTS idx_sale_transactions_sold_at ON sale_transactions(sold_at);
CREATE INDEX IF NOT EXISTS idx_stock_movements_sku ON stock_movements(sku);
CREATE INDEX IF NOT EXISTS idx_stock_movements_timestamp ON stock_movements(timestamp);
